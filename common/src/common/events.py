from datetime import datetime
from enum import StrEnum
from typing import Annotated, Literal
from uuid import UUID, uuid4

from pydantic import AwareDatetime, BaseModel, Field, StringConstraints

PlayerEventType = Literal["play", "pause", "stop"]


class BaseEvent(BaseModel):
    # consumers drop an event whose event_id they already saw (QoS 1 can deliver twice)
    event_id: UUID = Field(default_factory=uuid4)
    version: int = 1


class StreamStarted(BaseEvent):
    stream_id: int
    streamer_id: int
    streamer_name: str
    title: str
    game: str
    started_at: datetime


class StreamEnded(BaseEvent):
    stream_id: int
    streamer_id: int
    ended_at: datetime
    duration_s: float
    reason: Literal["normal", "error"]


class PlayerEvent(BaseEvent):
    stream_id: int
    event_type: PlayerEventType
    user_id: int | None
    occurred_at: datetime


# published by live-chat, consumed by search and stats; message_id is a uuid4 generated by live-chat
class ChatMessage(BaseEvent):
    message_id: UUID
    stream_id: int
    author_id: int
    author_name: str = Field(min_length=1)
    content: Annotated[
        str, StringConstraints(strip_whitespace=True, min_length=1, max_length=500)
    ]
    sent_at: AwareDatetime


# StrEnum rather than Literal: stats imports ItemType to type its routes
class ItemType(StrEnum):
    STREAMER = "streamer"
    MESSAGE = "message"


class TargetType(StrEnum):
    STREAMER = "streamer"
    REPLAY = "replay"


# published by search, consumed by stats; one event per item returned by a search
class SearchHit(BaseEvent):
    item_type: ItemType
    item_id: str = Field(min_length=1)
    query: str = Field(min_length=1)
    hit_at: AwareDatetime

# published by bookmarks, consumed by stats; one event per successful deletion
class BookmarkDeleted(BaseEvent):
    bookmark_id: int
    user_id: int
    target_type: TargetType
    target_id: int
    deleted_at: AwareDatetime
